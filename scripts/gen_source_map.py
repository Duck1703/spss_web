P("3. **`File3_Phan2.sav`:** `NDEAT` là chuỗi, bản ghi đầu chứa `H0` (rác) — cần sửa/xóa trước phân tích.")
P("4. **`File4_Phan2.sav`:** `HYPOTENSION`, `DEATH` lưu dạng chuỗi `'0'`/`'1'` — phải recode số trước khi")
P("   chạy mô hình.")
P("5. **`File1.sav`:** tên biến lệch bảng mã hóa trong PDF (vd `htuo`↔`C1 tuoi`, `csa`↔`C12 CSsau`)")
P("   nhưng thứ tự & nhãn giá trị khớp — ánh xạ theo vị trí, đã kiểm chứng từng biến.")
