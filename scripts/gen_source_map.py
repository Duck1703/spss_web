P("## 3. Kiểm kê 58 câu")
P()
P("| ID | Trang | Tóm tắt (không sao chép nguyên văn) | Dataset | Kỹ năng SPSS | Độ khó | Vai trò → Ngày |")
P("|---|---|---|---|---|---|---|")
for e in inv["exercises"]:
    if e["id"] == "P1-BONUS-SLNC":
        continue
    sk = ", ".join(e["skills"][:2])
    role = e["role"] + (f' → {e["day"]}' if e.get("day") else (" (extension)" if e["role"] == "deferred" else ""))
    P(f"| {e['id']} | {e.get('page') or '—'} | {e['summary']} | {e['dataset']} | {sk} | {e['difficulty']} | {role} |")
P()
P("## 4. Vấn đề dữ liệu phát hiện khi kiểm tra")
P()
P("1. **`GTinh` mã ngược:** trong `p1_B01_HA (1).sav`, `1 = Nữ, 2 = Nam` — khác trực giác phổ biến")
P("   (nam=1). Mọi bài lọc giới phải nhắc học viên kiểm tra nhãn trước.")
P("2. **`NNghiep` có lỗi nhập** (đúng như P1-Q14 kỳ vọng): giá trị `0` ×3 (ID 5, 184, 318),")
