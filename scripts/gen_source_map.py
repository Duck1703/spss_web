inv = json.load(open("curriculum/exercise-inventory.json", encoding="utf-8"))
L = []
def P(*a):
    L.append(" ".join(str(x) for x in a))

P("# EXERCISE-SOURCE-MAP — Kiểm kê 58 bài tập nguồn (Task 13)")
P()
P("> Tạo từ `curriculum/exercise-inventory.json` (machine-readable — cùng file này được website dùng")
P("> cho exercise card). Mọi ánh xạ dataset đã kiểm chứng bằng cách đọc trực tiếp file `.sav`")
P("> (pyreadstat): tên biến, nhãn biến, nhãn giá trị, số quan sát, missing.")
P("> **Quyền:** tài liệu gốc của bên thứ ba — file `.pdf`/`.sav` chỉ giữ local trong `exercises/`,")
P("> không commit, không publish; phân phối lại: NEEDS_OWNER_VERIFICATION.")
P()
P("## 1. Nguồn tài liệu đã kiểm tra")
P()
P("| Gói | PDF | Trang | Số câu | File .sav kèm theo |")
P("|---|---|---|---|---|")
P("| Package 1 | `exercises/bai_1/Bai thuc hanh SDH P1.pdf` | 5 | 43 (Câu 1–43) | `p1_B01_HA (1).sav` (620×40) · `P1_B02 CrossTab (2).sav` (4×3) · `P1_B03 ROC.sav` (30×5) · `So_Lieu_NC.sav` (360×38, phụ) |")
P("| Package 2 | `exercises/bai_2/BSNT_Bài TH_Phần 2_Cô Hiền.pdf` | 4 | 15 (Câu 1–15) + Bài TH3 không đánh số | `File1.sav` (50×18) · `File2_Phan2.sav` (12×3) · `File3_Phan2.sav` (20×2) · `File4_Phan2.sav` (30×5) · `File5_Phan2.sav` (296×7) |")
P()
P("## 2. Ánh xạ dataset → câu hỏi (đã kiểm chứng)")
P()
P("| File .sav | Câu hỏi dùng | Bằng chứng ánh xạ | Độ tin cậy |")
P("|---|---|---|---|")
P("| `p1_B01_HA (1).sav` | P1 Q01–Q14, Q17–Q20, Q22–Q43 | Có đủ mọi biến câu hỏi đòi: Tuoi, GTinh, HVan (không biết chữ), NNghiep, TTrang.KTe, 5 biến bệnh MT (nhị phân + danh mục Benh.MT_1/2), TSu.HA, HA 2 lần đo, CD.HA, Chieucao, Cannang, hút thuốc/rượu bia/muối/stress/TDTT | **VERIFIED** |")
P("| `P1_B02 CrossTab (2).sav` | P1-Q21 | 4 dòng × benh/phoinhiem/soluong = bảng 2×2 HPV–UTCTC trong PDF | **VERIFIED** (cần Weight Cases) |")
P("| `P1_B03 ROC.sav` | P1-Q15, Q16 | WBC/CRP/PCT + viemphoi (vi trùng/virus), n=30 đúng mô tả | **VERIFIED** |")
P("| `So_Lieu_NC.sav` | — (không câu nào) | Biến bộ STEPS khác (B7–F31); thiếu NNghiep, TTrang.KTe, bệnh MT → không thể trả lời Q05/Q07/Q14 | **VERIFIED = dataset phụ** |")
P("| `File1.sav` | P2 Q01–Q12 | 18 biến khớp 1:1 thứ tự phiếu điều tra & bảng mã hóa (omah…csa); n=50. PDF gọi \"File1_Phan 2.sav\" — cùng file | **VERIFIED** |")
P("| `File2_Phan2.sav` | P2-Q13 | 12 bệnh nhân × Sogio_cothuoc/Sogio_placebo — thiết kế ghép cặp | **VERIFIED** |")
P("| `File3_Phan2.sav` | P2-Q14 | PROCALCITONI + NDEAT; n=20. ⚠️ NDEAT có giá trị rác `H0` ở bản ghi đầu | **VERIFIED + cần làm sạch** |")
P("| `File4_Phan2.sav` | P2-Q15 | AGE, HYPOTENSION, PROCALCITONIN, DEATH; HYPOTENSION/DEATH là chuỗi 0/1 | **VERIFIED + cần recode** |")
